#' Simulated Electronic Health Record (EHR) Longitudinal Data
#'
#' A pre-generated long-format longitudinal dataset with 2000 subjects,
#' designed to look like an outpatient EHR extract for HbA1c. The dataset
#' is one replicate from the package's Monte Carlo simulation framework
#' (\code{simulations/simulation_study.R}), specifically the
#' \code{continuous_phi0} scenario (focal Z = NSES, phi = 0). It is generated
#' by \code{\link{sim_data_gen}} using an EHR-style covariate spec (Age,
#' Gender, Marital, Black, Hispanic, NSES) and the back-transform helper
#' that adds the \code{log_HbA1c} outcome column. The latent factor
#' \eqn{U_i}, frailty \eqn{\eta_i}, and per-process random effects that the
#' simulation generates internally are not retained in this user-facing
#' dataset, mirroring the situation in real EHR data.
#'
#' True parameter values used to generate the data are stored as an
#' attribute and can be retrieved with \code{attr(sim_ehr_data, "true_params")}.
#'
#' @format A \code{data.frame} with the following columns:
#' \describe{
#'   \item{id}{Integer subject identifier.}
#'   \item{Age}{Standardized age (z-score). Used by the modeling functions.}
#'   \item{Gender}{Binary indicator (1 = male, 0 = female).}
#'   \item{Marital}{Binary indicator (1 = married, 0 = not).}
#'   \item{Black}{Binary indicator (1 = Black race, 0 = otherwise).}
#'   \item{Hispanic}{Binary indicator (1 = Hispanic ethnicity, 0 = otherwise).}
#'   \item{NSES}{Continuous neighborhood socioeconomic status indicator
#'     (standardized median household income; mean 0, SD 1).}
#'   \item{time}{Visit time on the 0 to 120 window. \code{NA} for subjects
#'     with no visits.}
#'   \item{R}{Observation indicator at the visit (1 = HbA1c recorded,
#'     0 = not recorded).}
#'   \item{log_HbA1c}{Natural log of HbA1c, the recommended outcome for
#'     analysis. Built from the standardized linear outcome \eqn{Y} from
#'     the data-generating model via
#'     \code{log_HbA1c = log(5.6) + 0.05 * Y}.
#'     \code{NA} when \code{R = 0}.}
#'   \item{C}{Censoring time (end of follow-up window, 120 for all subjects).}
#' }
#'
#' @source Generated by \code{\link{sim_data_gen}} with the EHR-style
#'   covariate spec described in \code{data-raw/sim_ehr_data.R}, using the
#'   \code{continuous_phi0} scenario from \code{simulations/simulation_study.R}
#'   (\code{n = 2000}, \code{time.end = 120}, \code{phi = 0}, focal Z = NSES,
#'   seed = 21260509), then post-processed to add \code{log_HbA1c}.
#'
#' @examples
#' data(sim_ehr_data)
#' head(sim_ehr_data)
#'
#' # True data-generating parameters (named lists keyed by covariate name)
#' true <- attr(sim_ehr_data, "true_params")
#' true$beta
#'
#' @seealso \code{\link{sim_data_gen}} to generate new datasets with
#'   custom covariate sets and parameters.
